"""arena — a test environment that generates suboptimal programs and scores how well improve fixes them.

``generate(count, seed)`` writes one Python module with ``count`` functions drawn from five kinds:

  planted   a suboptimal form of an algorithm card (naive recursion, a loop with a closed form,
            trial division to n, ...) under a fresh name and with renamed parameters
  decoy     looks like a planted function but computes something else (off-by-one ranges,
            shifted sums, different seeds); substituting the look-alike card would be a bug.
            improve also matches a*card + b, so a decoy must differ from every such image on the
            small inputs every comparison includes: a sum that starts at 1 instead of 0 is card + 1,
            replaced correctly, and is no decoy
  optimal   an already-optimal form: improve must keep it (or find a faster verified one)
  rewrite   an expression with a cheaper equivalent under the rule cards
  shell     effectful code (files, sockets, clocks): must stay byte-identical

``run`` improves the module and scores it:
  soundness   end-to-end re-check passes · effect shell byte-identical · no decoy substituted
              with the look-alike card                                   (all must hold)
  recall      planted functions improved / planted functions
  speed       geometric mean speedup over improved functions (measured)

Honest limits (L1): the arena knows the answer only for the kinds it planted; speedups are
in-process CPython timings on this machine; a decoy can be *correctly* substituted by a different
card (e.g. range(1, n) sums are triangular numbers) and that is not counted as an error.
"""
from __future__ import annotations

import ast
import math
import random
from datetime import datetime, timezone

from . import values as V
from .context import Ctx
from .improve import improve_source, rename

DECOYS = [
    ("triangular", '''
def {name}({p0}: int) -> int:
    t = 0
    for i in range(2, {p0}):
        t += i
    return t'''),
    ("sum_1_to_n", '''
def {name}({p0}: int) -> int:
    s = 0
    for i in range(1, {p0} + 2):
        s += i
    return s'''),
    ("sum_of_squares", '''
def {name}({p0}: int) -> int:
    s = 0
    for i in range(1, {p0} + 1):
        s += i * i + 1
    return s'''),
    ("fibonacci", '''
def {name}({p0}: int) -> int:
    a = 2
    b = 1
    for _ in range({p0}):
        a, b = b, a + b
    return a'''),
    ("is_prime", '''
def {name}({p0}: int) -> bool:
    if {p0} < 2:
        return False
    for d in range(2, {p0}):
        if {p0} % d == 0:
            return d > 7
    return True'''),
    ("popcount", '''
def {name}({p0}: int) -> int:
    c = 0
    while {p0} > 1:
        c += {p0} & 1
        {p0} >>= 1
    return c'''),
]

OPTIMAL = [
    '''
def {name}({p0}: int) -> int:
    if {p0} <= 0:
        return 0
    return {p0} * ({p0} + 1) // 2''',
    '''
def {name}({p0}: int, {p1}: int) -> int:
    return abs({p0} - {p1})''',
    '''
def {name}({p0}: int) -> bool:
    return {p0} > 0 and ({p0} & ({p0} - 1)) == 0''',
]

REWRITES = [
    '''
def {name}({p0}: int, {p1}: int) -> int:
    return {p0} * {p1} + {p0} * 3''',
    '''
def {name}({p0}: int) -> int:
    return -(-{p0}) * 1 + 0''',
    '''
def {name}({p0}: int, {p1}: int) -> int:
    return ({p0} + {p1}) ** 2''',
]

SHELL = [
    '''
def {name}(path, record):
    with open(path, "a") as fh:
        fh.write(str(record) + "\\n")
    return True''',
    '''
def {name}(host, token):
    import socket
    s = socket.create_connection((host, 443), timeout=5)
    s.sendall(token.encode())
    return s''',
    '''
def {name}():
    import time
    return time.time()''',
]

PARAM_NAMES = ["n", "k", "x", "count", "value", "level", "size", "steps", "a", "b", "q", "z"]


def generate(ctx: Ctx, count: int, seed: int) -> tuple[str, dict]:
    """A module with ``count`` functions and the answer key."""
    rng = random.Random(seed)
    planted_cards = [c for c in ctx.store.cards("algorithm") if any(f.get("role") == "suboptimal" for f in c["forms"])]
    out = ['"""Generated by `cardmodel arena` (seed %d): a deliberately suboptimal module."""\n' % seed]
    key: dict = {}
    kinds = ["planted"] * 5 + ["decoy"] * 2 + ["optimal", "rewrite", "shell"]
    for i in range(count):
        kind = rng.choice(kinds)
        name = f"f{i:04d}_{kind}"
        if kind == "planted":
            card = rng.choice(planted_cards)
            form = rng.choice([f for f in card["forms"] if f.get("role") == "suboptimal"])
            old = [p["name"] for p in card["signature"]["params"]]
            used = {n.id for n in ast.walk(ast.parse(form["code"])) if isinstance(n, ast.Name)} - set(old)
            new = rng.sample([p for p in PARAM_NAMES if p not in used], len(old))
            code = rename(form["code"], {form["entry"]: name, **dict(zip(old, new))})
            key[name] = {"kind": kind, "card": card.qualified, "form": form["name"]}
        elif kind == "decoy":
            card_name, tpl = rng.choice(DECOYS)
            code = tpl.format(name=name, p0=rng.choice(PARAM_NAMES[:6]))
            key[name] = {"kind": kind, "not": f"algorithm/{card_name}"}
        elif kind == "optimal":
            p = rng.sample(PARAM_NAMES, 2)
            code = rng.choice(OPTIMAL).format(name=name, p0=p[0], p1=p[1])
            key[name] = {"kind": kind}
        elif kind == "rewrite":
            p = rng.sample(PARAM_NAMES, 2)
            code = rng.choice(REWRITES).format(name=name, p0=p[0], p1=p[1])
            key[name] = {"kind": kind}
        else:
            code = rng.choice(SHELL).format(name=name)
            key[name] = {"kind": kind}
        out.append(code.strip() + "\n")
    return "\n\n".join(out), key


def score(report: dict, key: dict) -> dict:
    fns = report["functions"]
    planted = [n for n, k in key.items() if k["kind"] == "planted"]
    improved = [n for n in planted if fns.get(n, {}).get("action", "kept") != "kept"]
    wrong_decoys = [n for n, k in key.items() if k["kind"] == "decoy"
                    and k["not"] in str(fns.get(n, {}).get("action", ""))]
    speedups = [f["speedup"] for f in fns.values() if f.get("speedup")]
    shell = [n for n, k in key.items() if k["kind"] == "shell"]
    shell_kept = all(any(e["name"] == n for e in report["effect_shell"]) for n in shell)
    sound = (report["end_to_end"].get("status") in ("pass", "nothing_changed") and report["effect_shell_identical"]
             and not wrong_decoys and shell_kept)
    reverted = sorted((report.get("reverted") or {}).keys())
    return {"functions": len(key), "planted": len(planted), "planted_improved": len(improved),
            "recall": round(len(improved) / len(planted), 4) if planted else None,
            "improved_total": len(speedups),
            "geomean_speedup": round(math.exp(sum(math.log(s) for s in speedups) / len(speedups)), 2)
            if speedups else None,
            "max_speedup": max(speedups) if speedups else None,
            "decoys": sum(1 for k in key.values() if k["kind"] == "decoy"), "decoys_wrongly_substituted": wrong_decoys,
            "shell_functions": len(shell), "shell_preserved": shell_kept,
            "end_to_end": report["end_to_end"].get("status"), "end_to_end_checks": report["end_to_end"].get("checks"),
            "effect_shell_identical": report["effect_shell_identical"], "sound": sound,
            "reverted_by_recheck": reverted}


def run(ctx: Ctx, count: int = 60, seed: int | None = None, samples: int = 24) -> dict:
    seed = V.fresh_seed() if seed is None else seed
    source, key = generate(ctx, count, seed)
    report = improve_source(ctx, source, f"arena_{seed}_{count}", seed=seed, samples=samples, native=False)
    sc = score(report, key)
    sc.update(seed=seed, count=count, finished=datetime.now(timezone.utc).isoformat(timespec="seconds"))
    return {"score": sc, "key": key, "report": report, "source": source}


def record(ctx: Ctx, result: dict, layer: str | None = None) -> str:
    sc = result["score"]
    name = f"arena_{sc['seed']}_{sc['count']}"
    ctx.store.save({"name": name, "category": "arena_run", "tier": 3,
                    "statement": f"arena run: {sc['planted_improved']}/{sc['planted']} planted improved, geomean "
                                 f"x{sc['geomean_speedup']}, sound={sc['sound']}",
                    "score": sc, "provenance": {"tool": "cardmodel arena"}}, layer=layer, category="arena_run")
    return f"arena_run/{name}"


def _count_defs(source: str) -> int:
    return sum(isinstance(n, ast.FunctionDef) for n in ast.parse(source).body)
