"""understanding — the roadmap of everything to understand about computation, from the bit upward.

The levels are cards (``cards/understanding``): each names the question it answers, the levels it builds on, what
mastering it means, and where CardModel touches it today. The order is the order of dependence: a level builds
only on levels with smaller numbers, so understanding expands outward from L00, the bit.

A level's status is computed, never typed (CM01):

* **mastered**: the level names an engine, and every one of its mastery criteria computes true now;
* **next**: not mastered, and every level it builds on is mastered (the frontier, where work goes first);
* **open**: everything else.

``render`` writes docs/UNDERSTANDING.md from the cards and from the mastered levels' own results.

Honest limits (L1): the map is a map, not a proof that nothing is missing; a level without an engine can be
"next" or "open" but never "mastered", however much related work the repository has.
"""
from __future__ import annotations

from . import bits as B

ENGINES = {"engines/bits.py": B}


def levels(store) -> list[dict]:
    view = store.registry("understanding")
    cards = [dict(c) for c in view.ALL.values()] if view else []
    return sorted(cards, key=lambda c: c["level"])


def problems(cards: list[dict]) -> list[str]:
    """The map's own consistency: unique numbers, known prerequisites, and dependence only downward."""
    out = []
    by_name = {c["name"]: c for c in cards}
    nums = [c["level"] for c in cards]
    if sorted(nums) != list(range(len(nums))):
        out.append(f"levels are not numbered 0..{len(nums) - 1}: {sorted(nums)}")
    for c in cards:
        if not c["name"].startswith(f"L{c['level']:02d}_"):
            out.append(f"{c['name']}: the name does not start with its level L{c['level']:02d}_")
        for b in c.get("builds_on") or []:
            if b not in by_name:
                out.append(f"{c['name']} builds on unknown level {b}")
            elif by_name[b]["level"] >= c["level"]:
                out.append(f"{c['name']} builds on {b}, which is not below it")
        if c["level"] > 0 and not c.get("builds_on"):
            out.append(f"{c['name']} builds on nothing, but only L00 may")
        if c.get("engine") and c["engine"] not in ENGINES:
            out.append(f"{c['name']} names engine {c['engine']}, which does not exist")
    return out


def assess(store, ops, results: dict | None = None) -> dict:
    """Every level with its computed status; mastered levels carry their criteria results."""
    cards = levels(store)
    results = dict(results or {})
    status: dict[str, str] = {}
    criteria: dict[str, list] = {}
    for c in cards:
        eng = c.get("engine")
        if eng in ENGINES:
            if eng not in results:
                results[eng] = ENGINES[eng].master(ops)
            crit = ENGINES[eng].mastery(results[eng], c["name"])
            texts = c.get("mastery") or []
            criteria[c["name"]] = [{**m, "claim": texts[i] if i < len(texts) else m["id"]}
                                   for i, m in enumerate(crit)]
            ok = len(crit) == len(texts) and all(m["ok"] for m in crit)
            status[c["name"]] = "mastered" if ok else "open"
    for c in cards:
        if status.get(c["name"]) == "mastered":
            continue
        pre = c.get("builds_on") or []
        status[c["name"]] = "next" if all(status.get(b) == "mastered" for b in pre) else "open"
    return {"levels": cards, "status": status, "criteria": criteria, "results": results,
            "problems": problems(cards)}


# -- docs/UNDERSTANDING.md ----------------------------------------------------------------------------------------
HEADER = """# UNDERSTANDING: the roadmap, from the bit upward

> Generated by `cardmodel basics roadmap --write docs/UNDERSTANDING.md` from `cards/understanding` and from the
> results of the mastered levels' engines. Edit the cards or the engines, not this file.

The owner's direction (2026-11-17): master the most basic of basics first, completely, with the model's own card
logic, and expand from there to everything as understanding grows. This document is the map of what there is to
understand about computation on computers and in programs, ordered so that every level builds only on levels
below it, and the record of what is mastered.

A level is **mastered** only when it has an engine and every one of its mastery criteria computes true from that
engine's results; that is checked every time this file is generated and by `tests/test_bits.py`. **Next** marks
the frontier: levels not yet mastered whose prerequisites all are. Nothing in a status column is typed by hand.
"""


def _fmt(n) -> str:
    return f"{n:,}"


def render(store, ops, results: dict | None = None) -> str:
    a = assess(store, ops, results)
    cards, status = a["levels"], a["status"]
    out = [HEADER]
    counts = {s: sum(1 for v in status.values() if v == s) for s in ("mastered", "next", "open")}
    out.append(f"**{len(cards)} levels: {counts['mastered']} mastered, {counts['next']} next, "
               f"{counts['open']} open.**\n")
    out.append("## 1. The map\n")
    part = None
    for c in cards:
        if c["part"] != part:
            part = c["part"]
            out.append(f"\n### {part}\n")
            out.append("| level | question | builds on | status | where CardModel touches it today |")
            out.append("|---|---|---|---|---|")
        pre = ", ".join(b.split("_")[0] for b in c.get("builds_on") or []) or "nothing"
        st = status[c["name"]]
        st = f"**{st}**" if st != "open" else st
        out.append(f"| {c['name'].split('_')[0]} {c['title']} | {c['question']} | {pre} | {st} | "
                   f"{'; '.join(c.get('in_repo') or [])} |")
    out.append("\n### What mastering each level means\n")
    for c in cards:
        out.append(f"* **{c['name'].split('_')[0]} {c['title']}.** " + " · ".join(c.get("mastery") or []))
    out.append(_bits_section(a))
    return "\n".join(out).rstrip() + "\n"


def _bits_section(a: dict) -> str:
    res = a["results"].get("engines/bits.py")
    if res is None:
        return ""
    by = {c["name"]: c for c in a["levels"]}
    l0, l1 = by.get("L00_bit", {}), by.get("L01_two_bit_functions", {})
    fns = res["functions"]
    suff = res["sufficiency"]
    laws = res["laws"]
    sole = suff["sole"]
    o = ["\n## 2. Why this is the smallest piece\n",
         f"* **L00, the bit.** {l0.get('why_here', '')}",
         f"* **L01, functions of two bits.** {l1.get('why_here', '')}",
         "* Everything above is built from it: a word is many bits (L04), arithmetic is circuits of these "
         "functions (L03, L05), memory is these functions with feedback (L08), and an instruction machine is one "
         "big function of this kind applied again and again (L10).\n",
         "## 3. L00 and L01, solved\n",
         "Run it with `cardmodel basics bits` (add `--save` to write the cards). The engine is "
         "`cardmodel/engines/bits.py`; the only things it is given are the bit, the op cards and the IR "
         "interpreter. Every claim below was computed on every input, so each is a proof, not a sample.\n",
         "### Mastery criteria, computed now\n", "| level | criterion | holds |", "|---|---|---|"]
    for name in ("L00_bit", "L01_two_bit_functions"):
        for m in a["criteria"].get(name, []):
            o.append(f"| {name.split('_')[0]} | {m['claim']} | {'yes' if m['ok'] else '**no**'} |")
    obs = ", ".join(f"{x['op']} = {B.LABELS.get(x['table'], x['table']) if x['arity'] == 2 else _obs_name(x)}"
                    for x in res["observed"])
    o += ["\n### What the op cards are, by observation\n",
          f"Running every op card with a bool rank through the IR interpreter on every row gives: {obs}. "
          f"{sum(1 for f in fns if f['op_cards'])} of the 16 functions have an op card; the other "
          f"{sum(1 for f in fns if not f['op_cards'])} are built below.\n",
          "### All 16 functions of two bits\n",
          "Rows are xy = 00, 01, 10, 11. *Over the op cards*: a smallest circuit over AND, OR, NOT, CMP_EQ and "
          "CMP_NE with the literals FALSE and TRUE (ties go to the cheaper op cards), checked by the IR "
          f"interpreter. *{' / '.join(sole)} gates*: the size of a smallest circuit using only that gate.\n",
          "| function | truth | depends on | op card | over the op cards | " + " | ".join(f"{g} gates" for g in sole)
          + " | Post classes |",
          "|---|---|---|---|---|" + "---|" * len(sole) + "---|"]
    for f in fns:
        post = ", ".join(POST_SHORT[k] for k, v in f["post"].items() if v) or "none"
        o.append(f"| {f['name']} | {''.join(map(str, f['truth']))} | {', '.join(f['inputs']) or 'nothing'} | "
                 f"{', '.join(f['op_cards']) or '–'} | `{B.show_term(f['over_op_cards']['term'])}` | "
                 + " | ".join(str(f["over_sole_gate"][g]["gates"]) for g in sole) + f" | {post} |")
    nand = next((f for f in fns if f["name"] == "XNOR"), None)
    searched = res["searched"]
    o += ["\n### Building everything from one gate\n",
          f"Of the {_fmt(suff['sets'])} sets of two-bit gates, {_fmt(suff['complete'])} build every function and "
          f"{_fmt(suff['sets'] - suff['complete'])} do not. The gates complete on their own are found, not given: "
          f"**{' and '.join(sole)}**, and neither has an op card. There are {len(suff['minimal_complete'])} "
          "minimal complete sets (no member can be dropped): "
          + ", ".join("{" + ", ".join(m) + "}" for m in suff["minimal_complete"]) + ".",
          f"\nNo set of functions that depend on at most one input is complete "
          f"({'confirmed' if not suff['unary_complete'] else '**contradicted**'} over all sets), which is why two "
          "bits is the smallest complete piece.\n",
          f"The searches are exhaustive by gate count, so each size in the table is a minimum. Programs tried "
          "per gate count: "
          + "; ".join(f"{g.replace('_', ' ')}: {', '.join(_fmt(x) for x in v)}" for g, v in searched.items()) + ".",
          (f"For example XNOR needs {nand['over_sole_gate'][sole[-1]]['gates']} {sole[-1]} gates "
           f"(`{nand['over_sole_gate'][sole[-1]]['program']}`), and every program with fewer was tried and "
           "failed." if nand else ""),
          "\n### Why a set of gates is incomplete\n",
          f"Ordering all {suff['closed_sets']} closed sets of two-bit functions, the model finds exactly "
          f"{len(suff['obstructions'])} maximal incomplete ones. A set of gates is complete exactly when it is "
          "inside none of them:\n"]
    for ob in suff["obstructions"]:
        o.append(f"* {{{', '.join(ob['members'])}}}: the functions that "
                 f"{', '.join(POST_TEXT.get(p, p) for p in ob['post_property']) or 'no property of Post names'}")
    inside = "; ".join(f"the self-dual functions lie inside the {', '.join(q.replace('_', ' ') for q in v)} ones"
                       if p == "self_dual" else f"{p} lies inside {', '.join(v)}"
                       for p, v in suff["post_inside"].items())
    o += [f"\nThese are Post's classes (1941), found here as structure, not taken from the theorem. Post names "
          f"five; for gates of two inputs only {len(suff['obstructions'])} are distinct ({inside}: every two-input "
          "self-dual function is a projection or a negation). Checked independently against Post's criterion "
          f"computed from its definitions: {suff['post_disagreements']} disagreements in {_fmt(suff['sets'])} sets.\n",
          "### Laws, found by enumeration\n",
          f"Every term over the op cards with up to {laws['size']} gates in three variables was enumerated; equal "
          f"truth tables give an equation. {_fmt(len(laws['laws']) + laws['derived'])} equations were found (counted "
          f"once up to renaming the variables); "
          f"{len(laws['laws'])} are kept as a basis and the other {_fmt(laws['derived'])} follow from them by "
          f"rewriting. Each is proved on all 8 rows. The textbook laws are among them, rediscovered rather than "
          "written in:\n"]
    red = B.rediscovered(res)
    o.append("| law | found |")
    o.append("|---|---|")
    for name, ok in red.items():
        l, r = B.CLASSIC[name]
        o.append(f"| {name}: `{B.show_term(l)} = {B.show_term(r)}` | {'yes' if ok else '**no**'} |")
    o.append("\nThe kept laws of size 1 and 2:\n")
    for law in laws["laws"]:
        if law["size"] <= 2:
            o.append(f"* `{B.law_text(law)}`")
    l2 = res["level2"]
    fa = l2["full_adder"]
    o += ["\n## 4. The next step: L02\n",
          "The search code takes the number of inputs as a parameter, so L02 starts from it. Already: every one "
          f"of the {l2['functions']} functions of three bits has a smallest formula over the 16 two-bit gates "
          f"({l2['found']} found, the largest needs {l2['max_size']} gates). The full adder, the first piece of "
          f"arithmetic (L03), falls out: sum `{fa['sum']['term']}` ({fa['sum']['size']} gates) and carry "
          f"`{fa['carry']['term']}` ({fa['carry']['size']} gates). These are formulas (no sharing); L02's "
          "criteria (smallest circuits, normal forms, the multiplexer, satisfiability) are what remains.\n",
          "## 5. Honest limits\n",
          "* L00 and L01 are mastered in the sense their criteria state: complete for functions of at most two "
          "bits, in gate count. Depth, fan-out and real hardware cost are not modelled yet.",
          f"* Laws are complete up to {laws['size']} gates per side in three variables; larger laws exist and are "
          "found by raising the size, at the cost of time.",
          "* The kept laws are a basis for the enumeration's rewriting, not a proven-minimal axiom system.",
          "* The roadmap is a map: it orders what we know of, and it will grow. A level is mastered only by an "
          "engine whose criteria compute true; related work elsewhere in the repository does not count."]
    return "\n".join(o)


POST_TEXT = {"preserves_false": "give FALSE when every input is FALSE",
             "preserves_true": "give TRUE when every input is TRUE",
             "monotone": "never fall when an input rises (monotone)",
             "affine": "are an XOR of inputs and a constant (affine)",
             "self_dual": "flip when every input flips (self-dual)"}
POST_SHORT = {"preserves_false": "keeps 0", "preserves_true": "keeps 1", "monotone": "monotone",
              "affine": "affine", "self_dual": "self-dual"}


def _obs_name(x: dict) -> str:
    if x["arity"] == 1:
        return {0b01: "NOT", 0b10: "identity", 0b00: "FALSE", 0b11: "TRUE"}.get(x["table"], str(x["table"]))
    return f"a function of {x['arity']} bits (table {x['table']:0{1 << x['arity']}b}, the multiplexer; L02)"
